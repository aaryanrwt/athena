"""Rebuild verified Rust PyO3 acceleration extensions in `.fast/ports/` into `.fast/lib/`.

Works cross-platform on Windows (`.pyd`), Linux (`.so`), and macOS (`.so`) using the
checked-in Rust crate sources generated by `fast-anything`. Athena automatically falls
back to pure Python if Rust extensions are not built or `FAST_ANYTHING_DISABLE=1` is set.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
import sys
import tomllib
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
FAST_DIR = REPO_ROOT / ".fast"


def _discover_enabled_ports() -> list[tuple[Path, str]]:
    state_file = FAST_DIR / "state.json"
    ports: list[tuple[Path, str]] = []
    if state_file.is_file():
        data = json.loads(state_file.read_text(encoding="utf-8"))
        for port in data.get("ports", {}).values():
            if not port.get("enabled"):
                continue
            crate_dir = REPO_ROOT / port["crate_dir"]
            if (crate_dir / "Cargo.toml").is_file():
                ports.append((crate_dir, str(port["ext"])))
    if ports:
        return sorted(ports, key=lambda item: item[1])

    ports_root = FAST_DIR / "ports"
    if not ports_root.is_dir():
        return []
    for manifest in sorted(ports_root.glob("*/Cargo.toml")):
        if "parse_unified_diff_raw" in manifest.parent.name:
            continue
        meta = tomllib.loads(manifest.read_text(encoding="utf-8"))
        lib_name = meta.get("lib", {}).get("name") or meta.get("package", {}).get("name")
        if lib_name:
            ports.append((manifest.parent, str(lib_name)))
    return ports


def main() -> int:
    cargo = shutil.which("cargo")
    if cargo is None:
        print("cargo not found on PATH; Athena will use pure-Python fallback.", file=sys.stderr)
        return 1

    ports = _discover_enabled_ports()
    if not ports:
        print("No enabled Rust ports found in .fast/.", file=sys.stderr)
        return 1

    target_dir = FAST_DIR / "target"
    lib_dir = FAST_DIR / "lib"
    lib_dir.mkdir(parents=True, exist_ok=True)
    release_dir = target_dir / "release"

    for crate_dir, ext_name in ports:
        manifest = crate_dir / "Cargo.toml"
        print(f"Building {ext_name} from {crate_dir.relative_to(REPO_ROOT)}...")
        subprocess.run(
            [cargo, "build", "--release", "--manifest-path", str(manifest), "--target-dir", str(target_dir)],
            check=True,
        )
        if sys.platform == "win32" or os.name == "nt":
            src = release_dir / f"{ext_name}.dll"
            dst = lib_dir / f"{ext_name}.pyd"
        elif sys.platform == "darwin":
            src = release_dir / f"lib{ext_name}.dylib"
            dst = lib_dir / f"{ext_name}.so"
        else:
            src = release_dir / f"lib{ext_name}.so"
            dst = lib_dir / f"{ext_name}.so"

        if not src.is_file():
            raise FileNotFoundError(f"Expected compiled library not found: {src}")
        shutil.copy2(src, dst)
        print(f"  -> {dst.relative_to(REPO_ROOT)}")

    print(f"Built {len(ports)} Rust extension(s) into {lib_dir.relative_to(REPO_ROOT)}.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
